"""Pydantic schemas for API requests, responses, tasks, and tool validation."""

from datetime import datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator


class CreateTaskArgs(BaseModel):
    """Validated arguments expected from Gemini for the `create_task` tool."""

    model_config = ConfigDict(extra="forbid")

    title: str = Field(
        ...,
        min_length=1,
        max_length=200,
        description="Short, clear title describing the task.",
    )
    due_date: str | None = Field(
        default=None,
        max_length=100,
        description="Optional due date string (for example, '2026-11-30' or 'tomorrow').",
    )

    @field_validator("title")
    @classmethod
    def validate_title(cls, value: str) -> str:
        """Ensure the task title is not blank whitespace."""
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Task title cannot be empty or whitespace.")
        return cleaned

    @field_validator("due_date")
    @classmethod
    def normalize_due_date(cls, value: str | None) -> str | None:
        """Trim due_date whitespace and convert empty strings to None."""
        if value is None:
            return None
        cleaned = value.strip()
        return cleaned or None


class Task(BaseModel):
    """Representation of a task stored in memory."""

    id: str = Field(..., description="Unique identifier generated by the backend.")
    title: str = Field(..., description="Task title.")
    due_date: str | None = Field(default=None, description="Optional due date.")
    created_at: datetime = Field(..., description="UTC timestamp when the task was created.")


class TaskListResponse(BaseModel):
    """Response payload for GET /tasks."""

    tasks: list[Task]
    count: int


class ToolExecutionRecord(BaseModel):
    """Audit record of a backend tool call executed during a /chat turn."""

    call_id: str
    tool_name: str
    arguments: dict[str, Any]
    success: bool
    result: dict[str, Any]


class ChatRequest(BaseModel):
    """Request payload for POST /chat."""

    message: str = Field(
        ...,
        min_length=1,
        max_length=4000,
        description="User message sent to MiniTask Agent.",
    )

    @field_validator("message")
    @classmethod
    def validate_message(cls, value: str) -> str:
        """Ensure the incoming chat message is not blank whitespace."""
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Message cannot be empty or whitespace.")
        return cleaned


class ChatResponse(BaseModel):
    """Response payload for POST /chat."""

    reply: str = Field(..., description="Natural-language response from Gemini.")
    interaction_id: str | None = Field(
        default=None,
        description="Gemini Interactions API ID for the final turn.",
    )
    tool_calls: list[ToolExecutionRecord] = Field(
        default_factory=list,
        description="Backend-verified tool executions performed during this request.",
    )
